# Regenerates lib/services/net/pinned_roots.dart: the public root CAs that the
# app trusts for the SOLIS server (Cloudflare Worker) host.
#
# Cloudflare issues edge certificates from Google Trust Services, Let's Encrypt,
# SSL.com and (advanced certificates) Sectigo, and rotates the leaf keys and the
# intermediates every few months. Pinning those would brick the app on the next
# rotation, so the app pins the ROOTS of those CAs instead (all valid into the
# 2030s and 2040s). Certificates are read from the local JDK trust store and the
# Windows root store; nothing is downloaded.
#
#   pwsh -File tool\make_tls_pins.ps1   (PowerShell 7: needs .NET for ExportSubjectPublicKeyInfo)
#
# Re-run when Cloudflare announces a new CA, then ship an app update well before
# the old roots stop being used (see docs/KEYS.md, "TLS pinning").
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root 'lib\services\net\pinned_roots.dart'
$jdk = 'C:\Program Files\Eclipse Adoptium\jdk-21.0.8.9-hotspot'
if ($env:JAVA_HOME -and (Test-Path (Join-Path $env:JAVA_HOME 'bin\keytool.exe'))) { $jdk = $env:JAVA_HOME }
$keytool = Join-Path $jdk 'bin\keytool.exe'

# JDK cacerts aliases.
$jdkAliases = @(
  'cn_gts_root_r1,o_google_trust_services_llc,c_us [jdk]',
  'cn_gts_root_r2,o_google_trust_services_llc,c_us [jdk]',
  'cn_gts_root_r3,o_google_trust_services_llc,c_us [jdk]',
  'cn_gts_root_r4,o_google_trust_services_llc,c_us [jdk]',
  'cn_isrg_root_x1,o_internet_security_research_group,c_us [jdk]',
  'cn_isrg_root_x2,o_internet_security_research_group,c_us [jdk]',
  'cn_sslcom_tls_rsa_root_ca_2022,o_ssl_corporation,c_us [jdk]',
  'cn_sslcom_tls_ecc_root_ca_2022,o_ssl_corporation,c_us [jdk]',
  'cn_sslcom_root_certification_authority_rsa,o_ssl_corporation,l_houston,st_texas,c_us [jdk]',
  'cn_sslcom_root_certification_authority_ecc,o_ssl_corporation,l_houston,st_texas,c_us [jdk]',
  'cn_sectigo_public_server_authentication_root_r46,o_sectigo_limited,c_gb [jdk]',
  'cn_sectigo_public_server_authentication_root_e46,o_sectigo_limited,c_gb [jdk]',
  'cn_usertrust_rsa_certification_authority,o_the_usertrust_network,l_jersey_city,st_new_jersey,c_us [jdk]',
  'cn_usertrust_ecc_certification_authority,o_the_usertrust_network,l_jersey_city,st_new_jersey,c_us [jdk]'
)
# GlobalSign Root CA (R1) cross-signs GTS Root R4; workers.dev sends that
# cross-signed chain today. Windows root store thumbprint:
$windowsThumbs = @('B1BC968BD4F49D622AA89A81F2150152A41D829C')

$certs = @()
foreach ($a in $jdkAliases) {
  $pem = & $keytool -exportcert -rfc -cacerts -storepass changeit -alias $a 2>$null
  if ($LASTEXITCODE -ne 0 -or -not $pem) { throw "Root not found in JDK trust store: $a" }
  $certs += [Security.Cryptography.X509Certificates.X509Certificate2]::new([Text.Encoding]::ASCII.GetBytes(($pem -join "`n")))
}
foreach ($t in $windowsThumbs) {
  $c = Get-ChildItem Cert:\LocalMachine\Root | Where-Object Thumbprint -eq $t
  if (-not $c) { throw "Root not found in Windows store: $t" }
  $certs += $c
}

$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine('// GENERATED by tool/make_tls_pins.ps1. Do not edit by hand.')
[void]$sb.AppendLine('//')
[void]$sb.AppendLine('// Root CAs trusted for the SOLIS server host (see PinnedHttp).')
[void]$sb.AppendLine('// Subject | not after | SHA-256 of the SubjectPublicKeyInfo (base64)')
$pems = [Text.StringBuilder]::new()
$sha = [Security.Cryptography.SHA256]::Create()
foreach ($c in ($certs | Sort-Object NotAfter)) {
  $spki = $c.PublicKey.ExportSubjectPublicKeyInfo()
  $pin = [Convert]::ToBase64String($sha.ComputeHash($spki))
  $cn = ($c.Subject -split ',')[0].Trim()
  [void]$sb.AppendLine("//   $cn | $($c.NotAfter.ToString('yyyy-MM-dd')) | $pin")
  $b64 = [Convert]::ToBase64String($c.RawData, 'InsertLineBreaks') -replace "`r", ''
  [void]$pems.AppendLine('-----BEGIN CERTIFICATE-----')
  [void]$pems.AppendLine($b64)
  [void]$pems.AppendLine('-----END CERTIFICATE-----')
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine("const pinnedRootCount = $($certs.Count);")
[void]$sb.AppendLine('')
[void]$sb.AppendLine("const pinnedRootsPem = '''")
[void]$sb.Append($pems.ToString())
[void]$sb.AppendLine("''';")
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, ($sb.ToString() -replace "`r", ''))
Write-Host "Wrote $($certs.Count) roots to $out"
